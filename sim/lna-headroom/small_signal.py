"""Stage-2 small-signal gain / NF / stability of the refined candidates (issue #132).

Reuses the ``sim/lna-sparam-nf`` conventions byte-identical: the bench's own two-port fixture
(power-wave S-parameters via Thevenin Z0 sources, noiseless reference source with the source noise
added analytically at T0 = 300.15 K) and its ``tb.json`` analyses and measurements (k / |Delta| / mu
in band, the 1-100 GHz stability sweep and the per-device operating point). The ONLY difference from
a production-bench deck is the DUT: the fixture's embedded verbatim ``lna_stage1`` block is replaced
by the candidate's frozen variant deck, and both source files are hash-pinned in the headroom plan.

Pure logic plus deck text and log parsing; no simulator. The comparison to C00 is descriptive:
no gain, NF or stability gate is introduced and no spec row is assessed here.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
import sys
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
SIM_DIR = BENCH_DIR.parent
REPO_ROOT = SIM_DIR.parent
SP_DIR = SIM_DIR / "lna-sparam-nf"
if str(SP_DIR) not in sys.path:
    sys.path.insert(0, str(SP_DIR))

import lna_nf  # noqa: E402

PREFIX = "sparam_"

_EMBED_RE = re.compile(
    r"(\* ==== BEGIN design/netlist/lna_stage1\.spice \(verbatim; do not edit here\) ====\n)"
    r"(.*?)"
    r"(\n\* ==== END design/netlist/lna_stage1\.spice ====)", re.S)

#: dB-like measures compared as candidate minus C00 (deltas in dB).
DELTA_GROUPS = {
    "s21_db": ("s21_db_lo", "s21_db_mid", "s21_db_hi"),
    "s11_db": ("s11_db_lo", "s11_db_mid", "s11_db_hi"),
    "s22_db": ("s22_db_lo", "s22_db_mid", "s22_db_hi"),
    "s12_db": ("s12_db_lo", "s12_db_mid", "s12_db_hi"),
    "msg_db": ("msg_db_lo", "msg_db_mid", "msg_db_hi"),
    "nf_db": ("nf_db_lo", "nf_db_mid", "nf_db_hi"),
}
#: stability quantities compared as absolute differences (dimensionless k / |Delta| / mu and
#: the 1-100 GHz sweep summary).
ABS_GROUPS = {
    "k": ("k_lo", "k_mid", "k_hi"),
    "delta": ("d_lo", "d_mid", "d_hi"),
    "mu": ("mu_lo", "mu_mid", "mu_hi"),
    "stability_sweep": ("sw_n", "sw_kmin", "sw_fkmin_ghz", "sw_kmin_hi", "sw_kmin_lo", "sw_dmax",
                        "sw_mumin", "sw_nunst"),
}
#: operating-point measures published per candidate (row 17 context; descriptive).
OP_MEASURES = ("q1_vce", "q2_vce", "q1_icfrac", "q2_icfrac", "idd_ma", "pdc_mw")


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def load_refs(hp: dict) -> tuple[str, dict]:
    """(fixture text, parsed manifest), each hash-checked against the frozen plan."""
    cfg = hp["refinement"]["small_signal"]
    texts = {}
    for key in ("fixture", "manifest"):
        p = REPO_ROOT / cfg[key]["file"]
        got = sha256_bytes(p.read_bytes())
        if got != cfg[key]["sha256"]:
            raise ValueError(f"{cfg[key]['file']} sha256 {got} != declared {cfg[key]['sha256']}")
        texts[key] = p.read_text()
    return texts["fixture"], json.loads(texts["manifest"])


def measure_names(tb: dict) -> list[str]:
    return list(tb["measure"])


def fixture_problems(fixture_text: str, tb: dict, dut_text: str) -> list[str]:
    """The structural checks plan_problems runs on the small-signal references."""
    out = []
    m = _EMBED_RE.search(fixture_text)
    if not m:
        out.append("small-signal fixture has no embedded DUT block")
    elif m.group(2) != dut_text.strip():
        out.append("small-signal fixture's embedded DUT is not the committed DUT")
    if "measure" not in tb or not tb["measure"]:
        out.append("small-signal manifest declares no measurements")
    if not tb.get("analyses"):
        out.append("small-signal manifest declares no analyses")
    return out


def variant_fixture(fixture_text: str, variant_deck: str) -> str:
    """The bench fixture with its embedded verbatim DUT replaced by ``variant_deck``.

    ``variant_deck`` is headroom.variant_text(dut, cand) for the candidate; the embedded-vs-DUT
    identity is checked by :func:`fixture_problems` before any deck is generated."""
    m = _EMBED_RE.search(fixture_text)
    if not m:
        raise ValueError("fixture has no embedded DUT block")
    return fixture_text[:m.start(2)] + variant_deck.strip("\n") + fixture_text[m.end(2):]


def body_text(tb: dict, fixture_text: str, cid: str, vdd_v: float) -> str:
    """One klt body: the (variant) fixture plus the bench's own .control block.

    Same construction as sim/lna-sparam-nf/run.py's klt_body (PVT params, fragment, analyses,
    ``let m_*``/``print m_*``), generated by this bench instead."""
    lines = [
        f"* {tb['name']}: klt sim body, lna-headroom stage-2 candidate {cid}, supply {vdd_v!r} V "
        "-- GENERATED by sim/lna-headroom/run.py, do not edit",
        f".param vdd_nom={tb['nominal_supply_v']!r}",
        f".param vdd_val={vdd_v!r}",
    ]
    lines += [f".param {k}={v}" for k, v in tb["params"].items()]
    lines += ["", fixture_text.rstrip("\n"), "", ".control", "set numdgt=10", "set noaskquit"]
    lines += [f"  {a}" for a in tb["analyses"]]
    lines += [f"  let m_{n} = {e}" for n, e in tb["measure"].items()]
    lines += [f"  print m_{n}" for n in tb["measure"]]
    lines += [".endc", ""]
    return "\n".join(lines)


def parse_measurements(text: str | None, names: list[str]) -> tuple[dict, list[str]]:
    """The declared m_* values of one small-signal log; every declared measure must be present,
    finite, and the log must carry the stability-sweep markers (deck finished)."""
    if text is None:
        return {}, ["no log"]
    vals = lna_nf.parse_log(text)
    problems = []
    if "SWEEP_BEGIN" not in text or "SWEEP_END" not in text:
        problems.append("stability-sweep markers missing (deck did not finish)")
    for n in names:
        v = vals.get(n)
        if v is None or not math.isfinite(v):
            problems.append(f"small-signal measurement {n} is missing or non-finite")
    return {n: vals[n] for n in names if n in vals}, problems


def compare(meas: dict, base: dict) -> dict:
    """Candidate minus C00: dB-like measures as dB deltas, stability quantities as absolute deltas."""
    out = {}
    for g, names in DELTA_GROUPS.items():
        out[g] = {n: meas[n] - base[n] for n in names}
    for g, names in ABS_GROUPS.items():
        out[g] = {n: meas[n] - base[n] for n in names}
    return out
