#!/usr/bin/env python3
"""klt-sim driver for the lna-sparam-nf bench (issue #22).

    python3 sim/lna-sparam-nf/run.py characterize --supersedes ID [--dry-run]
    python3 sim/lna-sparam-nf/run.py ingest REPORT.json [...] --supersedes ID

This driver predates `harness.cli run --backend batch` (issue #134), which now
sends any multi-point harness grid to the batch fleet the same way; it is kept
for this bench's correction/new-design notes and stage-1 tables. It expresses
the 27-point grid as `klt sim` requests (one per supply
value, 9 process x temperature corners each), then ingests the returned
per-corner logs into an ordinary harness-native record (corners/<id>/*.log,
netlist-snapshots/<id>.spice, records/<id>.md), exactly the layout
check_evidence_formats.py expects for this bench. The pattern is the one
sim/hbt-kaband-characterization/run.py established.

Ingest refuses to write unless all 27 points are present with finite values
for every declared measurement, and (when --supersedes is given) unless the
corrected values agree with the superseded record's logs under the linear-F
relation of lna_nf.py.

It also refuses (exit 3, before a record id or any log is written) unless the
klt reports themselves bind the simulation models to sim/pdk-artifact.json:
see harness.pdkartifact.verify_job_models. The ingesting host's own install
check is separate provenance and is never the record's artifact identity.
And it refuses (exit 1, equally before anything is written) if the working
testbench inputs changed after the run loaded them (issue #141): the record's
frozen netlist + manifest snapshots must describe the state the numbers came
from. A bare `ingest` reloads fresh (its drift is empty by construction), so
it additionally refuses unless every report's body deck is exactly what the
reloaded testbench would generate -- decks written by an earlier `characterize`
from a since-changed tb.json or netlist fragment must not have the ingest-time
manifest attached to their results.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import math
import shlex
import subprocess
import sys
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
SIM_DIR = BENCH_DIR.parent
REPO_ROOT = SIM_DIR.parent
sys.path.insert(0, str(SIM_DIR))
sys.path.insert(0, str(BENCH_DIR))

import lna_nf  # noqa: E402
import stage1_tables  # noqa: E402
from harness import evidence as evidence_mod  # noqa: E402
from harness.corners import CORNERS, PvtPoint, build_grid, resolve_corners, supply_points  # noqa: E402
from harness import klt_driver  # noqa: E402
from harness import pdkartifact  # noqa: E402
from harness.report import (  # noqa: E402
    RecordExists, allocate_record_id, build_record, git_provenance, write_manifest_snapshot,
    write_netlist_snapshot,
    write_record,
)
from harness.runner import PointResult, ngspice_version  # noqa: E402
from harness.testbench import load  # noqa: E402

SCRATCH = BENCH_DIR / "_build"


def klt_body(tb, vdd: float) -> str:
    """Self-contained klt circuit body for one supply value: the PVT params,
    the fixture text and the bench's own .control block (same analyses and
    `let m_*`/`print m_*` lines harness.runner.compose_deck would emit)."""
    lines = [
        f"* {tb.name}: klt sim body, supply {vdd:.2f} V -- GENERATED by run.py, do not edit",
        f".param vdd_nom={tb.nominal_supply_v!r}",
        f".param vdd_val={vdd!r}",
    ]
    lines += [f".param {k}={v}" for k, v in tb.params.items()]
    lines += ["", tb.netlist_data.decode("utf-8"), "", ".control", "set numdgt=10", "set noaskquit"]
    lines += [f"  {a}" for a in tb.analyses]
    lines += [f"  let m_{n} = {e}" for n, e in tb.measure.items()]
    lines += [f"  print m_{n}" for n in tb.measure]
    lines += [".endc", ""]
    return "\n".join(lines)


def klt_request(body_name, corners, temps, backend, timeout_s, stage_models, runner_version_check):
    """One klt sim request; sentinel `.meas tran` on the supply rail (see
    harness.klt_driver). The body's own .control block runs the real
    analyses first, as in the Ka-band driver."""
    return klt_driver.klt_request(
        body_name, [c.name for c in corners], temps, backend, timeout_s,
        sentinel_name="lna_rail_v", sentinel_node="v(vdd)",
        stage_models=stage_models, runner_version_check=runner_version_check)


def _pdk():
    return klt_driver.find_pdk_or_exit(SIM_DIR)


def _verified_pdk():
    """(pdk, verified artifact identity), or (pdk, None) after printing the refusal.

    Called BEFORE anything is submitted or written, the same refusal
    `harness.cli run` makes (exit 3): a record needs the hash-verified
    artifact identity (issue #103), and failing only inside `build_record`
    would leave an orphan corners/<record-id>/ log directory in the
    append-only evidence tree.
    """
    pdk = _pdk()
    try:
        return pdk, pdkartifact.verified_identity(pdk, SIM_DIR)
    except pdkartifact.ArtifactNotVerified as exc:
        print(str(exc), file=sys.stderr)
        return pdk, None


def cmd_characterize(args) -> int:
    tb = load(BENCH_DIR)
    verified = None
    if args.no_stage_models and not args.dry_run:
        # Without staging the runner simulates with its image-baked models and
        # the report carries no hash of them: ingest would refuse anyway.
        print("characterize: --no-stage-models leaves the runner's models unhashed, so no record "
              "could be written; nothing submitted", file=sys.stderr)
        return 3
    if not args.dry_run:  # a dry run submits and records nothing
        verified = _verified_pdk()
        if verified[1] is None:
            print("characterize: PDK artifact not verified; nothing submitted, no record written",
                  file=sys.stderr)
            return 3
    corners = resolve_corners(list(tb.corners))
    supplies = supply_points(tb.nominal_supply_v, tb.supply_tolerance)
    temps = list(tb.temperatures_c)
    stamp = _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%d-%H%M%S")
    work = (SCRATCH / f"klt-{stamp}").resolve()
    work.mkdir(parents=True, exist_ok=True)
    reports = []
    for vdd in supplies:
        tag = f"{vdd:.2f}v"
        body = work / f"body_{tag}.spice"
        body.write_text(klt_body(tb, vdd))
        req = work / f"request_{tag}.json"
        req.write_text(json.dumps(klt_request(
            body.name, corners, temps, args.backend, args.timeout_s,
            not args.no_stage_models, args.runner_version_check), indent=2) + "\n")
        out, resp = work / f"out_{tag}", work / f"report_{tag}.json"
        cmd = shlex.split(args.klt_cmd) + ["sim", str(req), "--backend", args.backend,
                                           "-o", str(out), "--format", "json"]
        print("$ " + " ".join(cmd), flush=True)
        if args.dry_run:
            continue
        with resp.open("w") as fh:
            proc = subprocess.run(cmd, stdout=fh, stderr=subprocess.PIPE, text=True)
        if proc.stderr:
            (work / f"stderr_{tag}.log").write_text(proc.stderr)
        print(f"  klt exit {proc.returncode}; report {resp}", flush=True)
        if proc.returncode != 0:
            print(proc.stderr[-4000:], file=sys.stderr)
            print(f"characterize: klt sim failed for supply {tag} (exit {proc.returncode}); "
                  f"no record written. Requests/bodies kept under {work}", file=sys.stderr)
            return 1
        reports.append((vdd, resp))
    if args.dry_run:
        print(f"--dry-run: requests and bodies written under {work}; nothing submitted")
        return 0
    return ingest(tb, reports, args, verified)


_body_supply = klt_driver.body_supply


def body_for(report_path: Path) -> Path:
    """The generated body deck a klt report was simulated from: characterize
    writes `body_<tag>.spice` beside every `report_<tag>.json`."""
    return report_path.with_name(
        report_path.name.replace("report_", "body_").replace(".json", ".spice"))


def cmd_ingest(args) -> int:
    tb = load(BENCH_DIR)
    reports = []
    for path in args.reports:
        path = Path(path).resolve()
        body = body_for(path)
        if not body.is_file():
            print(f"ingest: {body} is missing; the inputs the reports were simulated from "
                  "cannot be verified; NO record written", file=sys.stderr)
            return 1
        reports.append((_body_supply(body), path))
    return ingest(tb, reports, args)


def _offhost_artifact(loaded):
    """Verified identity of the models the off-host jobs actually used, or None
    after printing the refusal. Evaluated from the klt reports alone (see
    pdkartifact.verify_job_models); the ingesting host's install plays no part."""
    try:
        return pdkartifact.offhost_identity(
            [(path.name, report.get("environment") if isinstance(report, dict) else None)
             for _vdd, path, report in loaded], SIM_DIR)
    except pdkartifact.ArtifactNotVerified as exc:
        print(str(exc), file=sys.stderr)
        return None


def ingest(tb, reports, args, verified=None) -> int:
    # Publication gate (issue #141): characterize loaded the testbench before
    # the klt jobs ran and the frozen manifest snapshot must describe the
    # state the numbers came from, so refuse if the working inputs moved
    # meanwhile -- before a record id, log or snapshot is written. (A bare
    # `ingest` reloads fresh, so its drift is empty by construction; the
    # body-deck check below is what covers it.)
    drift = tb.working_input_drift()
    if drift:
        print(f"ingest: {drift}", file=sys.stderr)
        print("refusing to record: restore the working testbench inputs (or re-run "
              "characterize) so the frozen manifest snapshot describes the simulated state",
              file=sys.stderr)
        return 1
    # The bare-`ingest` half of the same gate (issue #141): its reports were
    # simulated from body decks an earlier `characterize` wrote, so a fresh
    # reload never shows drift -- but if tb.json or the netlist fragment
    # changed in between, the decks no longer match what this load would
    # generate, and the record would present the ingest-time manifest and
    # netlist as the inputs the numbers came from. Refuse unless every
    # report's body is exactly that deck.
    for vdd, resp_path in reports:
        body = body_for(resp_path)
        if not body.is_file():
            print(f"ingest: {body} is missing; the inputs the reports were simulated from "
                  "cannot be verified; NO record written", file=sys.stderr)
            return 1
        if body.read_text() != klt_body(tb, vdd):
            print(f"ingest: {body} was generated from different testbench inputs than the "
                  "working ones (tb.json or the netlist fragment changed after characterize); "
                  "re-run characterize; NO record written", file=sys.stderr)
            return 1
    # Ingest-host install: must itself be on the pin, but it is provenance of
    # THIS host only and never becomes the record's artifact identity.
    pdk, host_artifact = verified if verified is not None else _verified_pdk()
    if host_artifact is None:
        print("ingest: PDK artifact not verified; NO record written", file=sys.stderr)
        return 3
    loaded = [(vdd, path, json.loads(path.read_text())) for vdd, path in reports]
    # Simulation models: bound to the pin from the returned reports, BEFORE a
    # record id is allocated or any log is copied (issue #103).
    pdk_artifact = _offhost_artifact(loaded)
    if pdk_artifact is None:
        print("ingest: the off-host jobs' model closure is not verified against the pin; "
              "NO record written", file=sys.stderr)
        return 3
    started = _dt.datetime.now(_dt.timezone.utc)
    git = git_provenance(REPO_ROOT)
    expected = {p.corner_id: p for p in build_grid(
        resolve_corners(list(tb.corners)), tb.temperatures_c,
        supply_points(tb.nominal_supply_v, tb.supply_tolerance))}
    problems: list[str] = []
    results: dict[str, PointResult] = {}
    texts: dict[str, str] = {}
    klt_meta = []
    for vdd, resp_path, report in loaded:
        if "corners" not in report:
            problems.append(f"{resp_path.name}: no corners in klt report ({report.get('error')})")
            continue
        env = report.get("environment", {})
        klt_meta.append({"supply_v": vdd, "status": report.get("status"), "environment": env,
                         "klt_version": (report.get("provenance") or {}).get("klt_version")})
        for corner in report["corners"]:
            point = PvtPoint(corner=CORNERS[corner["process"]],
                             temp_c=float(corner["temperature_c"]), vdd=float(vdd))
            log_path = klt_driver.corner_log_path(corner, resp_path)
            if log_path is None:
                problems.append(f"{point.corner_id}: klt returned no log ({corner.get('diagnostics')})")
                continue
            text = log_path.read_text()
            meas = lna_nf.parse_log(text)
            missing = [n for n in tb.measure if n not in meas]
            nonfinite = [n for n, v in meas.items() if not math.isfinite(v)]
            if missing or nonfinite:
                problems.append(f"{point.corner_id}: missing {missing} / non-finite {nonfinite}")
                continue
            texts[point.corner_id] = text
            results[point.corner_id] = PointResult(
                point=point, status="ok", measurements={n: meas[n] for n in tb.measure},
                seconds=float(corner.get("runtime_s") or 0.0), deck="(klt sim body)",
                log=f"{point.corner_id}.log")
    missing_pts = sorted(set(expected) - set(results))
    if missing_pts:
        problems.append("missing PVT points: " + ", ".join(missing_pts))
    comparison = None
    if not problems and args.supersedes:
        old_dir = tb.experiment_dir / "corners" / args.supersedes
        comparison = lna_nf.compare_to_superseded(
            {cid: r.measurements for cid, r in results.items()}, old_dir)
        print(f"comparison with {args.supersedes}: {comparison['compared']} values compared; "
              f"worst {comparison['worst']}")
        problems += comparison["problems"]
    if problems:
        for p in problems[:40]:
            print(f"FAIL: {p}", file=sys.stderr)
        print("ingest: grid incomplete or invalid; NO record written", file=sys.stderr)
        return 1

    client = subprocess.run(shlex.split(args.klt_cmd) + ["--version"], capture_output=True, text=True)
    client_v = (client.stdout or client.stderr).strip()
    engines = sorted({str(m["environment"].get("engine_version")) for m in klt_meta})
    notes = list(tb.evidence.notes)
    nf_exprs = {n: e for n, e in tb.measure.items() if n.startswith("nf_db_")}
    for n, e in nf_exprs.items():
        if "300.15" not in e or not e.startswith("10*log10(1+"):
            raise SystemExit(f"error: tb.json {n} is not the corrected (issue #22) NF expression: {e}")
    if args.supersedes:
        notes.append(
            "CORRECTION RECORD (issue #22): this record supersedes "
            f"{args.supersedes} and is a FRESH simulation of the full 27-point HBT x T x V "
            "grid with the corrected NF method (noiseless Rs1, analytic F = 1 + inoise^2/(4 k 300.15 K Z0)); "
            "it is not a reprocessing of the old logs. The old record is untouched.")
    else:
        notes.append(
            "NEW-DESIGN RECORD (issue #28): this record supersedes NOTHING. The earlier lna-sparam-nf records "
            "(20260912-034726-9204518, 20261009-134024-57e1898) measure a different circuit (the unmatched "
            "single-CE placeholder, testbench/lna_ce_placeholder.spice) and stay valid as placeholder-methodology "
            "evidence; this record measures the xschem-derived design/lna_stage1 netlist. tb.json is re-pointed at "
            "that netlist by this record's commit; the old records are untouched.")
        notes.append(
            "NF expression used (post-#22, corrected): "
            + "; ".join(f"{n} = `{e}`" for n, e in sorted(nf_exprs.items()))
            + f". Introduced by commit aef3a6c (issue #22, record 20261009-134024-57e1898) and unchanged here "
            f"(checked at ingest: every nf_db_* expression starts `10*log10(1+` and carries T0 = 300.15 K). "
            f"This record was minted at git {git.get('commit', git.get('short', '?'))}.")
    if comparison:
        w, t = comparison["worst"], comparison["tolerances"]
        notes.append(
            f"Comparison with the superseded logs ({comparison['compared']} values over 27 corners): "
            f"F_new vs 10^(NF_old/10) - 27/300.15 agrees to max |dF| = {w['nf_f']:.3g} "
            f"(tolerance {t['nf_f']:g}; printed precision is 10 significant digits); "
            f"S-parameters max |d| = {w['sparam_db']:.3g} dB (tol {t['sparam_db']:g}); "
            f"k max |d| = {w['k']:.3g} (tol {t['k']:g}). The NF shift is a constant 27/300.15 = "
            f"{lna_nf.LEGACY_F_BIAS:.6f} in linear F, not a constant dB offset.")
    for m in klt_meta:
        e = m["environment"]
        remote = dict(e.get("remote") or {})
        notes.append(
            f"klt sim at supply {m['supply_v']:.2f} V: status {m['status']}, client `{client_v}`, "
            f"engine {e.get('engine')} {e.get('engine_version')}, client-side models_lib_sha256 "
            f"{e.get('models_lib_sha256')} (submitting host's top-level library, not runner "
            f"evidence), {len(e.get('staged_model_inputs') or [])} staged model inputs, "
            f"remote job {remote.get('job_id')} "
            f"({remote.get('provider')}, {remote.get('instance_type')}, runner klt "
            f"{remote.get('runner_klt_version')} vs client {remote.get('client_klt_version')}, "
            f"compatibility {remote.get('runner_compatibility')}).")
    notes.append(
        f"Simulation host: klt sim engine ngspice {', '.join(engines)} (off-host); the ingesting "
        f"host's own ngspice ({ngspice_version()}) did NOT produce these numbers and is recorded "
        "only as the ingest environment. No local re-simulation cross-check is possible on that "
        "version (the instance resistor temp= behaviour that motivated this correction is "
        "specific to ngspice-46; on the ingesting host's version the old and new methods agree).")
    notes.append(
        "PDK artifact provenance (issue #103), two separate facts: (1) simulation models -- every "
        f"file of {pdk_artifact['manifest']} matched by sha256 among each klt job's staged model "
        "inputs, with the runner on the client's klt build (see the '- PDK artifact:' line); the "
        "runner's own install was not hashed. (2) ingest host -- its own IHP install also matched "
        f"the pin (commit {host_artifact['upstream_commit'][:12]}); that is provenance of the "
        "ingesting host only and says nothing about the runner.")
    extensions = evidence_mod.BaseExtensions(
        record_kind=tb.evidence.record_kind, data_provenance=tb.evidence.data_provenance,
        extra=dict(tb.evidence.extra), notes=notes)
    extensions.validate()

    # Supplemental stage1 tables: rendered and validated in memory BEFORE any
    # permanent write (issue #130), so a measurement package without a usable
    # printed sweep, or whose sweep disagrees with the bench scalars, leaves no
    # record, corner directory or snapshot behind. Exit 4 = invalid package
    # (distinct from 1 = status/grid failure and 3 = provenance refusal).
    extra = ""
    if all(f"{d}_vce" in next(iter(results.values())).measurements for d in ("q1", "q2", "qr")):
        try:
            extra = stage1_tables.render(
                {cid: r.measurements for cid, r in results.items()}, texts,
                {cid: r.point.vdd for cid, r in results.items()},
                {cid: (r.point.corner.name, r.point.temp_c) for cid, r in results.items()})
        except ValueError as exc:
            print(f"error: invalid stage1 measurement package: {exc}", file=sys.stderr)
            print("ingest: NO record, corner logs or snapshot written", file=sys.stderr)
            return 4

    record_id = allocate_record_id(REPO_ROOT, tb.experiment_dir / "records", started, git)
    log_dir = tb.experiment_dir / "corners" / record_id
    if log_dir.exists():
        raise RecordExists(f"{log_dir} exists; append-only evidence is never rewritten")
    log_dir.mkdir(parents=True)
    for cid, text in sorted(texts.items()):
        (log_dir / f"{cid}.log").write_text(text)
    points = [expected[cid] for cid in sorted(expected)]
    ordered = [results[p.corner_id] for p in points]
    wall = (_dt.datetime.now(_dt.timezone.utc) - started).total_seconds()
    record = build_record(
        tb, pdk, points, ordered, f"{', '.join('ngspice-' + e for e in engines)} via klt sim "
        f"(ingested on {ngspice_version()})", REPO_ROOT, record_id, started.isoformat(), wall,
        claim=args.claim or tb.claim, supersedes=args.supersedes or "", git=git,
        extensions=extensions, pdk_artifact=pdk_artifact)
    write_netlist_snapshot(tb, tb.experiment_dir, record_id)
    write_manifest_snapshot(tb, tb.experiment_dir, record_id)
    path = write_record(record, tb.experiment_dir)
    if extra:
        with path.open("a") as fh:
            fh.write(extra)
    print(f"wrote {path}")
    return 0 if record["status"] == "pass" else 1


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    pc = sub.add_parser("characterize")
    pc.add_argument("--klt-cmd", default="klt")
    pc.add_argument("--backend", default="batch")
    pc.add_argument("--timeout-s", type=int, default=1800)
    pc.add_argument("--no-stage-models", action="store_true")
    pc.add_argument("--runner-version-check", default="", choices=("", "enforce", "warn"))
    pc.add_argument("--claim", default="")
    pc.add_argument("--supersedes", default="")
    pc.add_argument("--dry-run", action="store_true")
    pc.set_defaults(func=cmd_characterize)
    pi = sub.add_parser("ingest")
    pi.add_argument("reports", nargs="+")
    pi.add_argument("--klt-cmd", default="klt")
    pi.add_argument("--claim", default="")
    pi.add_argument("--supersedes", default="")
    pi.set_defaults(func=cmd_ingest)
    return p


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
