def _rf_substitution_probe(plan):
    """Measured V01-to-V03 substitutions, one at a time at the nominal probe point."""
    variants = {v["id"]: v["assignment"] for v in plan["variants"]}
    dut = PS.DUT_PATH.read_text()
    circuits, measures = [], []
    for name in ("V01", "Cshunt", "Cb2", "Cblk_in", "V03"):
        if name in variants:
            parts = variants[name]
        else:
            parts = variants["V01"] | {name: variants["V03"][name]}
        tag = name.lower()
        deck = PS.variant_dut_text(dut, parts, "").replace(".subckt lna_stage1 ", f".subckt iso_{tag} ")
        circuits += [deck, f"Xiso_{tag} pin_{tag} pout_{tag} vdd 0 iso_{tag}",
                     f"Vsrc_{tag} src_{tag} 0 DC 0 AC 1",
                     f"Rsrc_{tag} src_{tag} pin_{tag} 50", f"Rload_{tag} pout_{tag} 0 50"]
        measures += [f"let m_iso_s21_{tag} = db(2*v(pout_{tag}))", f"print m_iso_s21_{tag}"]
    return circuits, measures


def _probe_body(tb: dict, plan: dict) -> str:
    """One-corner probe of the substituted core's base impedance (input
    network dropped, excitation DC-blocked by a 1 F ideal cap so the bias
    network is untouched), plus the m= multiplier verification of cap_cmim."""
    assignment = {k: dict(v) for k, v in plan["variants"][0]["assignment"].items()}
    assignment["Cblk_in"] = {"kind": "drop"}
    assignment["Cshunt"] = {"kind": "drop"}
    assignment["Lin"] = {"kind": "drop"}
    header = [
        "* lna-passive-study prematch probe: Z_b of the substituted V01 core at the",
        "* DRAFT band centre (issue #340, option b re-match input) + cap m= check.",
        "* GENERATED by sim/lna-passive-study/run.py, do not edit.",
    ]
    dut = PS.variant_dut_text(PS.DUT_PATH.read_text(encoding="utf-8"), assignment,
                              "\n".join(header))
    dut = dut.replace(".subckt lna_stage1 in out vdd gnd",
                      ".subckt lna_probe b1 out vdd gnd")
    terminal_measures = []
    for tag in ("m", "e"):
        terminals = {"input_a": f"-i(vrf{tag})", "out_v": f"v(o{tag})",
                     "bulk_a": f"i(vbulk_{tag})"}
        for name, expression in terminals.items():
            for part in ("real", "imag"):
                vector = f"m_rf_{tag}_{name}_{part}"
                terminal_measures.extend([f"  let {vector} = {part}({expression})",
                                          f"  print {vector}"])
    iso_circuits, iso_measures = _rf_substitution_probe(plan)
    lines = [
        f".param vdd_nom={tb['nominal_supply_v']!r}",
        ".param vdd_val=2.5",
        "",
        dut.rstrip(),
        "",
        "Vdd vdd 0 DC {vdd_val}",
        "Xprobe b1 outp vdd 0 lna_probe",
        "Rs2 outp 0 50",
        "* base excitation: Thevenin 50 ohm through a 1 F ideal DC block (8 a-ohm at",
        "* 19.45 GHz: invisible in-band, no DC load on the bias divider)",
        "Vs1 s1n 0 DC 0 AC 1",
        "Rs1 s1n s1x 50",
        "Cblk1u s1x b1 1",
        "",
        "* subckt m= multiplier verification: one m=2 cap_cmim vs two explicit ones",
        "Vca can 0 DC 0 AC 1",
        "Xca can 0 cap_cmim w=6.16u l=6.16u m=2",
        "Vcb cbn 0 DC 0 AC 1",
        "Xcb1 cbn 0 cap_cmim w=6.16u l=6.16u",
        "Xcb2 cbn 0 cap_cmim w=6.16u l=6.16u",
        "",
        # Compare the complete three-terminal RF network at band centre.
        # A zero-volt source senses substrate current in each copy.
        *iso_circuits,
        "Vrfm im 0 AC 1",
        "Vbulk_m bm 0 0",
        "Rload_m om 0 50",
        "Xrfm im om bm cap_rfcmim w=74.8u l=74.8u m=119",
        "Vrfe ie 0 AC 1",
        "Vbulk_e be 0 0",
        "Rload_e oe 0 50",
        *(f"Xrfe{i} ie oe be cap_rfcmim w=74.8u l=74.8u" for i in range(119)),
        ".control",
        "set numdgt=10",
        "set noaskquit",
        "  op",
        "  ac lin 1 19.45e9 19.45e9",
        "  let m_vs = mag(v(s1n))",
        "  let m_vsx = mag(v(s1x))",
        "  let m_vb = mag(v(b1))",
        "  let m_zre = real(50*v(b1)/(v(s1n)-v(s1x)))",
        "  let m_zim = imag(50*v(b1)/(v(s1n)-v(s1x)))",
        *iso_measures,
        *terminal_measures,
        "  print m_vs m_vsx m_vb m_zre m_zim",
        "  ac lin 1 1e6 1e6",
        # ngspice's i(v) is the current INTO the source's + node, i.e. out of the
        # cap; the current into the device is -i(v), so C = +imag(-i)/(2 pi f).
        "  let m_ca_f = -imag(i(vca))/6.283185307/1e6",
        "  let m_cb_f = -imag(i(vcb))/6.283185307/1e6",
        "  print m_ca_f m_cb_f",
        ".endc",
        "",
    ]
    return "\n".join(lines)


def _grid_body(tb: dict, plan: dict, matches: dict[float, dict]) -> str:
    """The re-matched candidates in one deck, S11 forward-only per candidate
    (S11 needs no reverse pass)."""
    lines = [
        "* lna-passive-study prematch grid: on-chip cmim Cblk_in candidates, each with",
        "* its L-section re-match (Lin, Cshunt re-derived at 19.45 GHz from the probe),",
        "* S11 at the three DRAFT band points. GENERATED, do not edit.",
        f".param vdd_nom={tb['nominal_supply_v']!r}",
        ".param vdd_val=2.5",
        ".param z0=50",
        "",
        "* unloaded global rail: the klt sentinel grades v(vdd) on it",
        "Vdd vdd 0 DC {vdd_val}",
        "",
    ]
    for i, cblk_f in enumerate(sorted(matches)):
        m = matches[cblk_f]
        tag = f"c{i+1}"
        assignment = {k: dict(v) for k, v in plan["variants"][0]["assignment"].items()}
        assignment.update(rematch_assignment(m))
        header = [f"* prematch grid candidate {tag}: Cblk_in = {cblk_f:g} F, "
                  f"shunt and blocking capacitors use sized cap_cmim plates"]
        dut = PS.variant_dut_text(PS.DUT_PATH.read_text(encoding="utf-8"), assignment,
                                  "\n".join(header))
        dut = dut.replace(".subckt lna_stage1 in out vdd gnd",
                          f".subckt lna_{tag} in out vdd gnd")
        lines.append(dut.rstrip())
        lines.append("")
        lines.append(f"Vdd{tag} vdd{tag} 0 DC {{vdd_val}}")
        lines.append(f"Xdut{tag} p1{tag} p2{tag} vdd{tag} 0 lna_{tag}")
        lines.append(f"Vs1{tag} s1n{tag} 0 DC 0 AC 1")
        lines.append(f"Rs1{tag} s1n{tag} p1{tag} {{z0}} noisy=0")
        lines.append(f"Rs2{tag} p2{tag} 0 {{z0}}")
        lines.append("")
    lines.append(".control")
    lines.append("set numdgt=10")
    lines.append("set noaskquit")
    lines.append("  ac lin 3 17.7e9 21.2e9")
    for i in range(1, len(matches) + 1):
        lines.append(f"  let m_s11_db_lo_c{i} = db(mag(2*ac1.v(p1c{i})-1)[0])")
        lines.append(f"  let m_s11_db_mid_c{i} = db(mag(2*ac1.v(p1c{i})-1)[1])")
        lines.append(f"  let m_s11_db_hi_c{i} = db(mag(2*ac1.v(p1c{i})-1)[2])")
    for i in range(1, len(matches) + 1):
        for band in ("lo", "mid", "hi"):
            lines.append(f"  print m_s11_db_{band}_c{i}")
    lines.append(".endc")
    lines.append("")
    return "\n".join(lines)


