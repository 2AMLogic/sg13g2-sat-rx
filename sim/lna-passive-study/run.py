def assignment_for(plan_variant: dict, sizing: dict, prematch: dict | None) -> dict:
    """The plan's assignment, completed with V04's prematch-frozen values."""
    assignment = dict(plan_variant["assignment"])
    if plan_variant["id"] == "V04":
        if prematch is None or not prematch.get("selection"):
            raise CollectionError("V04 needs testbench/prematch.json with a selection")
        sel = prematch["selection"]
        assignment["Cblk_in"] = {
            "kind": "capacitor", "primitive": "cap_cmim",
            "side_um": sel["cblk_side_um"], "m": 1,
            "c_typ_f": sel["cblk_c_typ_f"],
        }
        assignment["Cshunt"] = {"kind": "ideal_value",
                                "value_text": _fmt_farads(sel["cshunt_f"])}
        assignment["Lin"] = {"kind": "ideal_value",
                             "value_text": _fmt_henries(sel["lin_h"])}
    return assignment


def _fmt_farads(value_f: float) -> str:
    for div, suffix in ((1e-12, "p"), (1e-9, "n"), (1e-15, "f"), (1e-6, "u")):
        if value_f >= div:
            return f"{value_f / div:.4g}{suffix}"
    return f"{value_f:.4g}"


def _fmt_henries(value_h: float) -> str:
    for div, suffix in ((1e-9, "n"), (1e-12, "p"), (1e-6, "u")):
        if value_h >= div:
            return f"{value_h / div:.4g}{suffix}"
    return f"{value_h:.4g}"


def variant_decks(plan: dict, sizing: dict, prematch: dict | None) -> dict[str, str]:
    """{variant id: frozen DUT deck text} for every variant that has all its
    inputs (V04 waits for the prematch outcome)."""
    dut = PS.DUT_PATH.read_text(encoding="utf-8")
    decks: dict[str, str] = {}
    for var in plan["variants"]:
        try:
            assignment = assignment_for(var, sizing, prematch)
        except CollectionError:
            continue
        header = [
            f"* SUBSTITUTED-PRIMITIVE VARIANT {var['id']} of design/netlist/lna_stage1.spice "
            f"(issue #340, sim/lna-passive-study): {var['description']}.",
            "* GENERATED by sim/lna-passive-study/run.py; NOT a production schematic; do not edit.",
            "* Sizings from layout/lna_stage1/passive_sizing.json (PDK models, corrections included).",
            "* The inductors (Lin, Lfeed, Le1) remain IDEAL lossless ngspice L: no PDK inductor",
            "* model exists (#110 / DR-0005). This deck selects nothing and claims no spec row.",
        ]
        decks[var["id"]] = PS.variant_dut_text(dut, assignment, "\n".join(header))
    return decks


def cmd_check_plan(args) -> int:
    plan = PS.load_plan()
    sizing = PS.load_sizing()
    problems = PS.plan_problems(plan, PS.DUT_PATH.read_text(encoding="utf-8"), sizing)
    for p in problems:
        print("FAIL:", p, file=sys.stderr)
    if problems:
        return 1
    print(f"plan ok: {len(plan['variants'])} candidate sets + control, "
          f"{len(PS.PROCESS_CORNERS)} processes x {len(PS.TEMPERATURES_C)} temps x "
          f"{len(PS.SUPPLIES_V)} supplies; method tb pinned by sha256; "
          f"sizing table pinned by sha256")
    return 0


def cmd_variants(args) -> int:
    plan = PS.load_plan()
    sizing = PS.load_sizing()
    prematch = json.loads(PS.PREMATCH_PATH.read_text()) if PS.PREMATCH_PATH.is_file() else None
    decks = variant_decks(plan, sizing, prematch)
    PS.VARIANTS_DIR.mkdir(parents=True, exist_ok=True)
    bad = 0
    for vid, text in sorted(decks.items()):
        path = PS.VARIANTS_DIR / f"{vid}.spice"
        if args.check:
            if not path.is_file() or path.read_text() != text:
                print(f"FAIL: {path.name} does not regenerate from the plan + sizing "
                      f"+ prematch", file=sys.stderr)
                bad += 1
        else:
            path.write_text(text)
    expected = {v["id"] for v in plan["variants"]}
    missing = expected - set(decks)
    if missing:
        print(f"note: {sorted(missing)} wait for testbench/prematch.json (V04)", flush=True)
    if not args.check:
        print(f"wrote {len(decks)} variant decks under {PS.VARIANTS_DIR}")
    return 1 if bad else 0


