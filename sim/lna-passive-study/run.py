def _write_record(plan, rec, cells, reports, work) -> None:
    rid = rec["record_id"]
    RECORDS.mkdir(parents=True, exist_ok=True)
    if (RECORDS / f"{rid}.md").exists():
        raise RecordExists(f"{RECORDS / (rid + '.md')} exists")
    md = _render_md(rec)
    # stored evidence: per-cell logs + snapshot package
    stage = PS.SIM_DIR / ".work" / ".stage" / "lna-passive-study" / "sim" / "lna-passive-study"
    snap = stage / "netlist-snapshots" / rid
    snap.mkdir(parents=True, exist_ok=True)
    logdir = stage / "corners" / rid
    logdir.mkdir(parents=True, exist_ok=True)
    files: list[tuple[Path, str]] = []
    prefix = "sim/lna-passive-study"
    for ck, meas in sorted(cells.items()):
        p = logdir / f"{ck}.log"
        p.write_text(json.dumps(meas, indent=0, sort_keys=True) + "\n")
        files.append((p, f"{prefix}/corners/{rid}/{ck}.log"))
    # per-cell machine sidecar (stored, not committed: bulk data)
    gz = stage / f"{rid}-cells.json.gz"
    with gzip.open(gz, "wt", encoding="utf-8") as fh:
        json.dump(cells, fh, sort_keys=True)
    files.append((gz, f"{prefix}/records/{rid}-cells.json.gz"))
    for key, rp in sorted(reports.items()):
        if key.startswith("prematch_"):
            name = key[len("prematch_"):]
            base = rp.parent
            for src_name, dst_name in (
                    (f"body_{name}.spice", f"body_{name}.spice"),
                    (f"request_{name}.json", f"request_{name}.json"),
                    (rp.name, f"report_{name}.json")):
                src = base / src_name
                if src.is_file():
                    dst = snap / dst_name
                    dst.write_bytes(src.read_bytes())
                    files.append((dst, f"{prefix}/netlist-snapshots/{rid}/{dst_name}"))
            continue
        base = rp.parent
        for src_name, dst_name in (
                (f"body_{key}.spice", f"body_{key}.spice"),
                (f"request_{key}.json", f"request_{key}.json"),
                (rp.name, f"report_{key}.json")):
            src = base / src_name
            if src.is_file():
                dst = snap / dst_name
                dst.write_bytes(src.read_bytes())
                files.append((dst, f"{prefix}/netlist-snapshots/{rid}/{dst_name}"))
    for extra, dst_name in ((PS.PLAN_PATH, "plan.json"), (PS.PREMATCH_PATH, "prematch.json")):
        if extra.is_file():
            dst = snap / dst_name
            dst.write_bytes(extra.read_bytes())
            files.append((dst, f"{prefix}/netlist-snapshots/{rid}/{dst_name}"))
    control_deck = PS.control_dut_text(PS.DUT_PATH.read_text(encoding="utf-8"))
    (snap / "control_V00.spice").write_text(control_deck)
    files.append((snap / "control_V00.spice",
                  f"{prefix}/netlist-snapshots/{rid}/control_V00.spice"))
    for vid in rec["variants"]:
        src = PS.VARIANTS_DIR / f"{vid}.spice"
        dst = snap / f"variant_{vid}.spice"
        dst.write_bytes(src.read_bytes())
        files.append((dst, f"{prefix}/netlist-snapshots/{rid}/variant_{vid}.spice"))

    # the record's Markdown is written by the store (it appends the Stored
    # evidence section from the manifest); the JSON sidecar only after the
    # store accepted every byte, so a store failure leaves no half-record.
    try:
        store_mod.preflight(PS.REPO_ROOT, klt="klt")
    except store_mod.StoreError as exc:
        print(f"EVIDENCE STORE UNAVAILABLE -- nothing committed (fail closed): {exc}",
              file=sys.stderr)
        return 10
    store_mod.store_files(
        files, repo_root=PS.REPO_ROOT, bench="lna-passive-study", rid=rid,
        summary_text=md, summary_path=RECORDS / f"{rid}.md", klt="klt")
    (RECORDS / f"{rid}.json").write_text(json.dumps(rec, indent=1, sort_keys=True) + "\n")
    print(f"wrote {RECORDS / (rid + '.md')}")
    print(f"wrote {RECORDS / (rid + '.json')}")


def cmd_verify(args) -> int:
    ids = args.records or sorted(
        p.name[: -len(".json")] for p in RECORDS.glob("*.json"))
    bad = 0
    for rid in ids:
        rec = json.loads((RECORDS / f"{rid}.json").read_text())
        md = (RECORDS / f"{rid}.md").read_text(encoding="utf-8")
        problems = _verify_one(rec, md)
        for p in problems:
            print(f"FAIL {rid}: {p}", file=sys.stderr)
            bad += 1
    if not bad:
        print(f"verify: {len(ids)} record(s) reproduce")
    return 1 if bad else 0


def _verify_one(rec: dict, md: str) -> list[str]:
    problems: list[str] = []
    if rec.get("spec_rows_claimed_met") != []:
        problems.append("spec_rows_claimed_met must be []")
    if rec["status"] not in PS.STATUSES or f"- **Status: {rec['status']}**" not in md:
        problems.append("status invalid or not stated in the Markdown")
    if md.splitlines()[:1] != [f"# lna-passive-study record {rec['record_id']}"]:
        problems.append("first line must be '# lna-passive-study record <id>'")
    for sec in ("Declaration", "Controls and method identity",
                "Comparative deltas at the row bound cells (variant - control)",
                "Worst-case deltas per variant (over the bound cells)",
                "Provenance and stored evidence", "Stored evidence"):
        if f"## {sec}" not in md:
            problems.append(f"missing required section '## {sec}'")
    for needle in ("IDEAL", "No spec row is claimed", "COMPARATIVE DELTAS ONLY"):
        if needle not in rec["claim"] or needle not in md:
            problems.append(f"claim must state {needle!r}")
    plan = PS.load_plan()
    declared = [v["id"] for v in plan["variants"]]
    if not set(rec["variants"]) <= set(declared):
        problems.append("record publishes variants outside the frozen plan")
    for vid in rec["variants"]:
        deck = PS.VARIANTS_DIR / f"{vid}.spice"
        if not deck.is_file() or PS.sha256_text(deck.read_text()) != \
                rec["variant_deck_sha256"][vid]:
            problems.append(f"{vid}: committed deck does not match the record's hash")
        # deltas re-derive from the sidecar's own cells (embedded in deltas +
        # gates re-checkable): recompute worst over the record's bound cells
        bound = {ck for group in rec["bound_cells"][vid].values() for ck in group}
        worst = {}
        for name in PS.DELTA_MEASURES:
            values = [row[name] for ck, row in rec["deltas"][vid].items()
                      if name in row and ck in bound]
            if values:
                worst[name] = {"min": round(min(values), 4), "max": round(max(values), 4)}
        if worst != rec["worst"][vid]:
            problems.append(f"{vid}: published worst-case deltas do not re-derive")
    if rec["status"] == "COLLECTED" and not rec["gates"]["pass"]:
        problems.append("status COLLECTED but gates did not pass")
    return problems


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0],
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--klt-cmd", default="klt")
    p.add_argument("--timeout-s", type=int, default=1800)
    p.add_argument("--wait-for-capacity", type=int, default=600,
                   help="seconds each batch submit waits for fleet capacity "
                        "(host rule: 600)")
    p.add_argument("--capacity-retries", type=int, default=2)
    sub = p.add_subparsers(dest="command", required=True)
    for name in ("check-plan", "variants"):
        q = sub.add_parser(name)
        q.add_argument("--check", action="store_true")
        q.set_defaults(func=globals()[f"cmd_{name.replace('-', '_')}"])
    for name in ("prematch", "build", "collect", "verify"):
        q = sub.add_parser(name)
        q.add_argument("--dry-run", action="store_true")
        if name == "build":
            q.add_argument("--workdir", default=None)
        if name == "verify":
            q.add_argument("records", nargs="*")
        q.set_defaults(func=globals()[f"cmd_{name.replace('-', '_')}"])
    args = p.parse_args(argv)
    return args.func(args)


