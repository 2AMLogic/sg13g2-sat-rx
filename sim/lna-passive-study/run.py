def assignment_for(plan_variant: dict, sizing: dict, prematch: dict | None) -> dict:
    """The plan's assignment, completed with V04's prematch-frozen values."""
    assignment = dict(plan_variant["assignment"])
    if plan_variant["id"] == "V04":
        if prematch is None or not prematch.get("selection"):
            raise CollectionError("V04 needs testbench/prematch.json with a selection")
        sel = prematch["selection"]
        assignment.update(rematch_assignment(prematch["rematches"][f"{sel['cblk_f']:g}"]))
    return assignment


def rematch_assignment(match: dict) -> dict:
    """Use the same drawn components in the screen and the frozen V04 deck."""
    return {
        "Cblk_in": {"kind": "capacitor", "primitive": "cap_cmim",
                    "side_um": match["side_um"], "m": match["plates"],
                    "c_typ_f": match["c_typ_f"]},
        "Cshunt": {"kind": "capacitor", "primitive": "cap_cmim",
                   "side_um": match["shunt_side_um"], "m": 1,
                   "c_typ_f": match["shunt_c_typ_f"]},
        "Lin": {"kind": "ideal_value", "value_text": _fmt_henries(match["lin_h"])},
    }


def _fmt_henries(value_h: float) -> str:
    for div, suffix in ((1e-9, "n"), (1e-12, "p"), (1e-6, "u")):
        if value_h >= div:
            return f"{value_h / div:.4g}{suffix}"
    return f"{value_h:.4g}"


def variant_decks(plan: dict, sizing: dict, prematch: dict | None) -> dict[str, str]:
    """{variant id: frozen DUT deck text} for every variant that has all its
    inputs (V04 waits for the prematch outcome)."""
    dut = PS.DUT_PATH.read_text(encoding="utf-8")
    decks: dict[str, str] = {}
    for var in plan["variants"]:
        try:
            assignment = assignment_for(var, sizing, prematch)
        except CollectionError:
            continue
        header = [
            f"* SUBSTITUTED-PRIMITIVE VARIANT {var['id']} of design/netlist/lna_stage1.spice "
            f"(issue #340, sim/lna-passive-study): {var['description']}.",
            "* GENERATED by sim/lna-passive-study/run.py; NOT a production schematic; do not edit.",
            "* Sizings from layout/lna_stage1/passive_sizing.json (PDK models, corrections included).",
            "* The inductors (Lin, Lfeed, Le1) remain IDEAL lossless ngspice L: no PDK inductor",
            "* model exists (#110 / DR-0005). This deck selects nothing and claims no spec row.",
        ]
        decks[var["id"]] = PS.variant_dut_text(dut, assignment, "\n".join(header))
    return decks


