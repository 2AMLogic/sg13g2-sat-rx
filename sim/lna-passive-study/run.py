def _requests(plan: dict, sizing: dict, prematch: dict | None, work: Path, args):
    """Every (key, request path) of the study: control + variants + the two
    prematch requests (re-submitted only if their reports are absent)."""
    tb = json.loads(PS.METHOD_TB.read_text(encoding="utf-8"))
    out: list[tuple[str, Path]] = []
