def _requests(plan: dict, sizing: dict, prematch: dict | None, work: Path, args):
    """Every (key, request path) of the study: control + variants + the two
    prematch requests (re-submitted only if their reports are absent)."""
    tb = json.loads(PS.METHOD_TB.read_text(encoding="utf-8"))
    out: list[tuple[str, Path]] = []
    decks = {"V00": PS.control_dut_text(PS.DUT_PATH.read_text(encoding="utf-8"))}
    decks.update(variant_decks(plan, sizing, prematch))
    for vid in ["V00"] + [v["id"] for v in plan["variants"]]:
        if vid not in decks:
            continue
        for vdd in PS.SUPPLIES_V:
            key = f"{vid}_{vdd:.2f}v"
            body = work / f"body_{key}.spice"
            note = (f"* candidate set {vid} of sim/lna-passive-study (issue #340); "
                    f"selects nothing; inductors stay IDEAL")
            body.write_text(PS.body_text(f"lna-passive-study {vid}", decks[vid], tb,
                                         vdd, note))
            req = work / f"request_{key}.json"
            req.write_text(json.dumps(PS.klt_request(
                body.name, [c["name"] for c in PS.PROCESS_CORNERS],
                list(PS.TEMPERATURES_C), args.timeout_s, _osdi_abs_path()), indent=2) + "\n")
            out.append((key, req))
    return out


def cmd_build(args) -> int:
    plan = PS.load_plan()
    sizing = PS.load_sizing()
    prematch = json.loads(PS.PREMATCH_PATH.read_text()) if PS.PREMATCH_PATH.is_file() else None
    work = Path(args.workdir or SCRATCH / "collect")
